<?php

declare(strict_types=1);

namespace ElevenLabs\Types;

use ElevenLabs\Core\Json\JsonSerializableType;
use ElevenLabs\Core\Json\ReflectiveSerialization;
use ElevenLabs\Core\Json\JsonProperty;

/**
 * The reflective deserializer reconstructs this model with `new static($values)`, so a subclass has
 * to keep a constructor it can call with one associative array.
 *
 * @phpstan-consistent-constructor
 */
class PreviewAudioDbModel extends JsonSerializableType
{
  use ReflectiveSerialization;

  #[JsonProperty('voice_id')]
  public ?string $voiceId;

  #[JsonProperty('text')]
  public ?string $text;

  #[JsonProperty('audio_url', required: true)]
  public string $audioUrl;

  #[JsonProperty('hls_manifest_url')]
  public ?string $hlsManifestUrl;

  #[JsonProperty('dash_manifest_url')]
  public ?string $dashManifestUrl;

  #[JsonProperty('is_auto_generated')]
  public ?bool $isAutoGenerated;

  #[JsonProperty('generated_at_unix')]
  public ?int $generatedAtUnix;

  /**
   * @param array{
   *   audioUrl: string,
   *   voiceId?: ?string,
   *   text?: ?string,
   *   hlsManifestUrl?: ?string,
   *   dashManifestUrl?: ?string,
   *   isAutoGenerated?: ?bool,
   *   generatedAtUnix?: ?int,
   * } $values
   */
  public function __construct(array $values)
  {
    $this->voiceId = $values['voiceId'] ?? null;
    $this->text = $values['text'] ?? null;
    $this->audioUrl = $values['audioUrl'];
    $this->hlsManifestUrl = $values['hlsManifestUrl'] ?? null;
    $this->dashManifestUrl = $values['dashManifestUrl'] ?? null;
    $this->isAutoGenerated = $values['isAutoGenerated'] ?? null;
    $this->generatedAtUnix = $values['generatedAtUnix'] ?? null;

    $this->_dirtyFields = [
      'audio_url' => true
    ];
    if (array_key_exists('voiceId', $values)) {
      $this->_dirtyFields['voice_id'] = true;
    }
    if (array_key_exists('text', $values)) {
      $this->_dirtyFields['text'] = true;
    }
    if (array_key_exists('hlsManifestUrl', $values)) {
      $this->_dirtyFields['hls_manifest_url'] = true;
    }
    if (array_key_exists('dashManifestUrl', $values)) {
      $this->_dirtyFields['dash_manifest_url'] = true;
    }
    if (array_key_exists('isAutoGenerated', $values)) {
      $this->_dirtyFields['is_auto_generated'] = true;
    }
    if (array_key_exists('generatedAtUnix', $values)) {
      $this->_dirtyFields['generated_at_unix'] = true;
    }
  }

  public function toMultipart(): array
  {
    $parts = [];
    if ($this->voiceId !== null) {
      $parts[] = [
        'name' => 'voice_id',
        'contents' => $this->voiceId
      ];
    }

    if ($this->text !== null) {
      $parts[] = [
        'name' => 'text',
        'contents' => $this->text
      ];
    }

    $parts[] = [
      'name' => 'audio_url',
      'contents' => $this->audioUrl
    ];

    if ($this->hlsManifestUrl !== null) {
      $parts[] = [
        'name' => 'hls_manifest_url',
        'contents' => $this->hlsManifestUrl
      ];
    }

    if ($this->dashManifestUrl !== null) {
      $parts[] = [
        'name' => 'dash_manifest_url',
        'contents' => $this->dashManifestUrl
      ];
    }

    if ($this->isAutoGenerated !== null) {
      $parts[] = [
        'name' => 'is_auto_generated',
        'contents' => $this->isAutoGenerated ? 'true' : 'false'
      ];
    }

    if ($this->generatedAtUnix !== null) {
      $parts[] = [
        'name' => 'generated_at_unix',
        'contents' => (string) $this->generatedAtUnix
      ];
    }

    return $parts;
  }

  public function validate(): void
  {
  }
}

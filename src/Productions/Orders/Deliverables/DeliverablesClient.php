    $response = $this->sendJsonRequest(
      new JsonApiRequest(
        baseUrl: $this->getBaseUrl($resolvedConfig),
        path: '/v1/productions/orders/' .
          \ElevenLabs\Core\Client\RawClient::encodePathParam($orderId) .

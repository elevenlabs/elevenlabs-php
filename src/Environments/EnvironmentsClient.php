   */
  public function delete(string $environment, ?array $options = null): void
  {
    $resolvedConfig = $this->getResolvedConfig($this->deleteConfig, $options);
    $response = $this->sendJsonRequest(
      new JsonApiRequest(
        baseUrl: $this->getBaseUrl($resolvedConfig),
        path: '/v1/convai/environments/' .
          \ElevenLabs\Core\Client\RawClient::encodePathParam($environment),
        method: HttpMethod::DELETE
      ),
      $resolvedConfig
